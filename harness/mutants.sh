#!/usr/bin/env bash
# Sensitivity check for the property suite: plant faults an agent might introduce into Order, one
# at a time, and record which property checks catch each one.
#
#   make up && harness/mutants.sh            # writes results/mutants/
#
# Each mutant is a one-line edit of services/order/app.py, saved as M<n>.patch. It is copied into
# the running Order container, which is restarted; then harness/evaluate.py runs both suites once.
# Order is recreated from its image at the end, so the stack is back to Version 0.
set -euo pipefail
cd "$(dirname "$0")/.."

APP=services/order/app.py
OUT=results/mutants
mkdir -p "$OUT"

NAMES=(
  "retry cap raised from 3 to 6"
  "timeouts removed (1 s per attempt -> 10 s, 2.5 s deadline -> 30 s)"
  "new idempotency key on every charge attempt"
  "stock never released after a failed checkout"
  "stale-order reaper removed"
  "DB statement timeout raised from 1 s to 10 s"
)
EDITS=(
  's/^MAX_ATTEMPTS = 3 /MAX_ATTEMPTS = 6 /'
  's/^ATTEMPT_TIMEOUT = 1.0 /ATTEMPT_TIMEOUT = 10.0 /; s/^CHECKOUT_DEADLINE = 2.5 /CHECKOUT_DEADLINE = 30.0 /'
  's/resp = await app.state.http.post(url, \*\*kwargs)/resp = await app.state.http.post(url, **{**kwargs, "headers": {k: v + f"-{attempt}" for k, v in kwargs.get("headers", {}).items()}})/'
  's/elif release:/elif False:/'
  's/asyncio.create_task(reaper())/asyncio.create_task(asyncio.sleep(1e9))/'
  's/^DB_TIMEOUT = 1.0 /DB_TIMEOUT = 10.0 /'
)

restart_order() {
  docker compose restart order >/dev/null 2>&1
  for _ in $(seq 30); do curl -sf localhost:8000/health >/dev/null && return; sleep 1; done
  echo "order did not become healthy" >&2; exit 1
}
fresh_order() { docker compose up -d --force-recreate --wait order >/dev/null 2>&1; }

tmp=$(mktemp -d); trap 'rm -rf "$tmp"; fresh_order' EXIT
summary="$OUT/summary.md"
{
  echo "# Planted faults (mutants) in the Order service"
  echo
  echo "Generated by \`harness/mutants.sh\` at commit \`$(git rev-parse --short HEAD)\`. Each mutant is"
  echo "one edit of \`$APP\` (see \`M<n>.patch\`); both suites ran once against it (\`M<n>/run-1.json\`)."
  echo
  echo "| Mutant | Fault | Functional | Properties | Caught by |"
  echo "|---|---|---|---|---|"
} > "$summary"

for i in "${!NAMES[@]}"; do
  n=$((i + 1))
  sed -e "${EDITS[$i]}" "$APP" > "$tmp/app.py"
  if cmp -s "$APP" "$tmp/app.py"; then echo "M$n: edit did not apply" >&2; exit 1; fi
  diff -u --label "a/$APP" --label "b/$APP" "$APP" "$tmp/app.py" > "$OUT/M$n.patch" || true

  fresh_order
  docker compose cp "$tmp/app.py" order:/app/order/app.py >/dev/null 2>&1
  restart_order
  python3 harness/evaluate.py --out "$OUT/M$n" --runs 1 >/dev/null || true
  rm -f "$OUT/M$n/summary.json"

  row=$(python3 - "$OUT/M$n/run-1.json" <<'EOF'
import json, re, sys
run = json.load(open(sys.argv[1]))["suites"]
f, p = run["functional"], run["properties"]
caught = sorted({re.match(r".*::test_(p\d+)", t).group(1).upper()
                 for t, r in p["tests"].items() if r["outcome"] != "passed"}, key=lambda s: int(s[1:]))
print(f"{f['passed']}/{f['total']} | {p['passed']}/{p['total']} | {', '.join(caught) or 'none'}")
EOF
)
  echo "| M$n | ${NAMES[$i]} | $row |" >> "$summary"
  echo "M$n ${NAMES[$i]}: $row"
done
